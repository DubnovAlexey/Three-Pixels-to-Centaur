// =====================================================================
// FILE: tools/make-image-previews.mjs
// PURPOSE: light previews for card images: assets/images/preview/<name>.webp, 720 px wide.
// Cards pick the preview or the original through srcset (js/imageCard.js); full-size views
// (archive lightbox, dossiers, "open the portrait") keep the original files.
// SECTIONS: 1 inputs; 2 encoding; 3 generated module js/imagePreviews.js.
// Needs ffmpeg/ffprobe with libwebp on PATH. Re-run after adding or replacing images:
//   npm run images:previews
// Why: originals are up to 2560 px wide but cards show 230–500 px. Decoding and scaling the
// extra pixels caused long frames while scrolling and cost phones several megabytes.
// =====================================================================
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// BEGIN inputs
const root = fileURLToPath(new URL('../', import.meta.url));
const imageDir = path.join(root, 'assets/images');
const previewDir = path.join(imageDir, 'preview');
const PREVIEW_WIDTH = 720;
const MIN_SOURCE_WIDTH = 760; // narrower originals are light enough already
const QUALITY = '78';
// END inputs

// BEGIN probe: width and height of an image file
function probe(file) {
  const [width, height] = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0',
    '-show_entries', 'stream=width,height', '-of', 'csv=p=0', file], { encoding: 'utf8' }).trim().split(',').map(Number);
  return { width, height };
}
// END probe

// BEGIN encoding
mkdirSync(previewDir, { recursive: true });
const entries = {};
let savedBytes = 0;
const names = readdirSync(imageDir).filter(name => name.endsWith('.webp') && !name.startsWith('favicon')).sort();
for (const name of names) {
  const source = path.join(imageDir, name);
  const { width, height } = probe(source);
  const target = path.join(previewDir, name);
  if (width < MIN_SOURCE_WIDTH) { rmSync(target, { force: true }); continue; }
  if (!existsSync(target) || statSync(target).mtimeMs < statSync(source).mtimeMs) {
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', source, '-vf', `scale=${PREVIEW_WIDTH}:-2:flags=lanczos`,
      '-c:v', 'libwebp', '-quality', QUALITY, '-compression_level', '6', target]);
  }
  const previewBytes = statSync(target).size;
  const sourceBytes = statSync(source).size;
  if (previewBytes >= sourceBytes) { rmSync(target); continue; } // no gain: the card keeps the original
  savedBytes += sourceBytes - previewBytes;
  entries[`assets/images/${name}`] = { width, height, preview: `assets/images/preview/${name}`, previewWidth: PREVIEW_WIDTH };
}
// Previews of removed originals are deleted too.
for (const name of readdirSync(previewDir)) {
  if (!entries[`assets/images/${name}`]) rmSync(path.join(previewDir, name));
}
// END encoding

// BEGIN generated module
const body = `// FILE: js/imagePreviews.js — generated by tools/make-image-previews.mjs, do not edit by hand.
// PURPOSE: original image → light 720-px preview for card srcset; full-size views keep the original.
export const imagePreviews = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(path.join(root, 'js/imagePreviews.js'), body, 'utf8');
console.log(`Previews: ${Object.keys(entries).length} of ${names.length} images, cards ${(savedBytes / 1048576).toFixed(1)} MB lighter in total.`);
// END generated module
